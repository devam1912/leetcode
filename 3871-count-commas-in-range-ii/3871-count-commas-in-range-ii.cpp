class Solution {
public:
    long long countCommas(long long n) {
        if (n < 1000) return 0;
        
        long long ans = 0;

        // 1000 → 999,999 (1 comma)
        if (n >= 1000)
            ans += (min(n, 999999LL) - 1000 + 1) * 1;

        // 1,000,000 → 999,999,999 (2 commas)
        if (n >= 1000000)
            ans += (min(n, 999999999LL) - 1000000 + 1) * 2;

        // 1,000,000,000 → 999,999,999,999 (3 commas)
        if (n >= 1000000000)
            ans += (min(n, 999999999999LL) - 1000000000 + 1) * 3;

        // 1,000,000,000,000 → 999,999,999,999,999 (4 commas)
        if (n >= 1000000000000LL)
            ans += (min(n, 999999999999999LL) - 1000000000000LL + 1) * 4;

        // 1,000,000,000,000,000 → ... (5 commas)
        if (n >= 1000000000000000LL)
            ans += (n - 1000000000000000LL + 1) * 5;

        return ans;
    }
};